alter table public.freights
  add column if not exists empty_return_amount numeric(12, 2) not null default 0;

alter table public.freights drop constraint if exists freights_freight_value_check;
alter table public.freights drop constraint if exists freights_operation_values_check;
alter table public.freights
  add constraint freights_operation_values_check check (
    (operation_kind = 'freight' and freight_value > 0 and empty_return_amount = 0)
    or
    (operation_kind = 'empty_return' and freight_value = 0 and (
      (equipment_type = 'carreta_ls' and empty_return_amount = 300)
      or (equipment_type = 'bitrem_30m' and empty_return_amount = 400)
    ))
  );

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  category text not null check (category in ('personal_hygiene', 'breakfast', 'lunch', 'dinner', 'varied')),
  expense_date date not null,
  amount numeric(12, 2) not null check (amount > 0),
  notes text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists expenses_date_idx on public.expenses (expense_date desc);
alter table public.expenses enable row level security;
revoke all on public.expenses from anon, authenticated;
