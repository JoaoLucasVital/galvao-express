create table if not exists public.carriers (
  id bigint generated by default as identity primary key,
  name text not null unique,
  phone text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.freights (
  id bigint generated by default as identity primary key,
  carrier_id bigint not null references public.carriers(id) on delete restrict,
  cte_number text not null default '',
  type text not null default 'Frete' check (type = 'Frete'),
  operation_kind text not null default 'freight' check (operation_kind in ('freight', 'empty_return')),
  equipment_type text not null default 'carreta_ls' check (equipment_type in ('bitrem_30m', 'carreta_ls')),
  origin text not null,
  destination text not null,
  freight_value numeric(12, 2) not null,
  empty_return_amount numeric(12, 2) not null default 0,
  commission_percent numeric(5, 2) not null default 15 check (commission_percent in (13, 15)),
  commission_value numeric(12, 2)
    generated always as (round(freight_value * commission_percent / 100, 2)) stored,
  notes text not null default '',
  freight_date date not null,
  loading_at timestamp without time zone not null default localtimestamp,
  status text not null default 'concluido',
  commission_status text not null default 'recebida' check (commission_status = 'recebida'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint freights_equipment_commission_check check (
    (equipment_type = 'bitrem_30m' and commission_percent = 13)
    or (equipment_type = 'carreta_ls' and commission_percent = 15)
  ),
  constraint freights_operation_values_check check (
    (operation_kind = 'freight' and freight_value > 0 and empty_return_amount = 0)
    or
    (operation_kind = 'empty_return' and freight_value = 0 and (
      empty_return_amount > 0
    ))
  )
);

create table if not exists public.expenses (
  id bigint generated by default as identity primary key,
  category text not null check (category in ('personal_hygiene', 'breakfast', 'lunch', 'dinner', 'varied')),
  expense_date date not null,
  amount numeric(12, 2) not null check (amount > 0),
  notes text not null default '',
  created_at timestamptz not null default now()
);

create or replace function public.set_freights_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists freights_set_updated_at on public.freights;
create trigger freights_set_updated_at
before update on public.freights
for each row execute function public.set_freights_updated_at();

create index if not exists freights_date_idx on public.freights (freight_date desc);
create index if not exists freights_loading_at_idx on public.freights (loading_at desc);
create index if not exists freights_carrier_idx on public.freights (carrier_id);
create index if not exists freights_equipment_idx on public.freights (equipment_type);
create index if not exists expenses_date_idx on public.expenses (expense_date desc);

